  await page.getByRole("button", { name: "Accept all questions with answers", exact: true }).click();
  await expect(page.locator(".bank-question")).toHaveCount(1);
  await page.reload();
  await page.getByRole("button", { name: "Skip review & study", exact: true }).click();
  await page.getByRole("button", { name: "Go to question 3", exact: true }).click();
  await page.locator(".answer-option").first().click();
