test("practice grades a shuffled answer by ID, orders mistakes first, and persists on reload", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (e) => errors.push(e.message));
  await sample(page);
  await page.getByLabel("Shuffle answers").check();
  await page.getByLabel("Number of questions").fill("2");
  await page.getByRole("button", { name: "Start studying" }).click();
  await expect(page.getByRole("button", { name: "Check answer" })).toBeDisabled();
  await expect(page.getByText("B is correct.", { exact: false })).not.toBeVisible();
  await page.getByRole("button", { name: /Active recall/ }).click();
  const order = await page.locator(".answer-option").allTextContents();
  await page.reload();
  await expect(page.getByRole("button", { name: /Active recall/ })).toHaveAttribute("aria-pressed", "true");
  expect(await page.locator(".answer-option").allTextContents()).toEqual(order);
  await page.getByRole("button", { name: "Check answer" }).click();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Correct", exact: true })).toBeVisible();
  await expect(page.getByText("B is correct.", { exact: false })).toBeVisible();
  await expect(page.getByRole("button", { name: /Active recall/ })).toBeDisabled();
  await page.getByRole("button", { name: "Next", exact: true }).click();
  await page.getByRole("button", { name: /Studying everything in one long session/ }).click();
  await page.getByRole("button", { name: "Check answer" }).click();
  await page.getByRole("button", { name: "See results", exact: true }).click();
  await page.reload();
  await expect(page.getByText("1 out of 2", { exact: true })).toBeVisible();
  await expect(page.locator(".result-question").first()).toContainText("What does spaced practice mean?");
  await expect(page.locator(".result-question").last()).toContainText("Which study technique");
  await page.getByRole("button", { name: "Practice mistakes" }).click();
  await expect(page.locator(".progress-heading")).toContainText("Question 1 of 1");
  await expect(page.getByRole("heading", { name: "What does spaced practice mean?" })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: "What does spaced practice mean?" })).toBeVisible();
  expect(await page.evaluate(() => localStorage.getItem("recall.workspace.v2"))).toBeTruthy();
  expect(await page.evaluate(() => Object.keys(sessionStorage))).toEqual([]);
  expect(errors).toEqual([]);
});

